class EmptyOrb {
    constructor() {
        this.math = 0;
        this.scie = 0;
        this.ensh = 0;
        this.sost = 0;
        this.buec = 0;
        this.engi = 0;
        this.prog = 0;
        this.special = 0;
    }

    getMath() {
        return this.math;
    }

    getScie() {
        return this.scie;
    }

    getEnsh() {
        return this.ensh;
    }

    getSost() {
        return this.sost;
    }

    getBuec() {
        return this.buec;
    }

    getEngi() {
        return this.engi;
    }

    getProg() {
        return this.prog;
    }

    getSpecial() {
        return this.special;
    }
}

export default EmptyOrb;